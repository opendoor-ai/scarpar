insert into public.categories (org_id, name, slug, parent_id, sort_order)
select org.id, src.name, src.slug, parent.id, src.sort_order
  from src
  cross join org
  join public.categories parent
    on parent.org_id = org.id and parent.slug = src.parent_slug and parent.parent_id is null
 where not exists (
         select 1 from public.categories c
          where c.org_id = org.id and c.parent_id = parent.id and c.name = src.name
       )
on conflict (org_id, slug) do nothing;

-- 확인용: 1차별 2차 카테고리 수
select p.name as 일차_카테고리, count(c.id) as 이차_카테고리_수
  from public.categories p
  left join public.categories c on c.parent_id = p.id
 where p.parent_id is null
   and p.org_id = (select id from public.orgs where slug = 'jadong')
 group by p.name, p.sort_order, p.created_at
 order by p.sort_order, p.created_at;
